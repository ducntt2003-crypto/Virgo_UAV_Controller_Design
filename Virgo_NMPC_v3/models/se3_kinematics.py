#!/usr/bin/env python3
"""
==============================================================================
 SE(3) and SO(3) Kinematics Library for Virgo OMAV
 Compatible with both pure NumPy and CasADi symbolic graphs.
==============================================================================
 Coordinates:
   - World Frame (W): North-East-Down (NED)
   - Body Frame (B): Centered at vehicle CoM (X: Forward, Y: Right, Z: Down)
   - Unit Quaternion Convention: q = [qw, qx, qy, qz]^T (Hamiltonian)
==============================================================================
"""

import math
import numpy as np
import casadi as cs


def skew_casadi(w):
    """Returns skew-symmetric matrix [w]_\times for a 3x1 CasADi vector."""
    return cs.vertcat(
        cs.horzcat(0.0, -w[2], w[1]),
        cs.horzcat(w[2], 0.0, -w[0]),
        cs.horzcat(-w[1], w[0], 0.0)
    )


def skew_numpy(w):
    """Returns skew-symmetric matrix [w]_\times for a 3-element NumPy array."""
    return np.array([
        [0.0, -w[2], w[1]],
        [w[2], 0.0, -w[0]],
        [-w[1], w[0], 0.0]
    ], dtype=float)


def quat_to_rot_casadi(q):
    """
    Converts unit quaternion q = [qw, qx, qy, qz]^T to 3x3 rotation matrix R_WB.
    Maps vectors from Body frame B to World frame W: v_W = R_WB * v_B.
    """
    qw, qx, qy, qz = q[0], q[1], q[2], q[3]

    r00 = 1.0 - 2.0 * (qy**2 + qz**2)
    r01 = 2.0 * (qx * qy - qw * qz)
    r02 = 2.0 * (qx * qz + qw * qy)

    r10 = 2.0 * (qx * qy + qw * qz)
    r11 = 1.0 - 2.0 * (qx**2 + qz**2)
    r12 = 2.0 * (qy * qz - qw * qx)

    r20 = 2.0 * (qx * qz - qw * qy)
    r21 = 2.0 * (qy * qz + qw * qx)
    r22 = 1.0 - 2.0 * (qx**2 + qy**2)

    return cs.vertcat(
        cs.horzcat(r00, r01, r02),
        cs.horzcat(r10, r11, r12),
        cs.horzcat(r20, r21, r22)
    )


def quat_to_rot_numpy(q):
    """Converts unit quaternion q = [qw, qx, qy, qz] to 3x3 rotation matrix (NumPy)."""
    q = q / np.linalg.norm(q)
    qw, qx, qy, qz = q
    return np.array([
        [1.0 - 2.0*(qy**2 + qz**2), 2.0*(qx*qy - qw*qz),     2.0*(qx*qz + qw*qy)],
        [2.0*(qx*qy + qw*qz),     1.0 - 2.0*(qx**2 + qz**2), 2.0*(qy*qz - qw*qx)],
        [2.0*(qx*qz - qw*qy),     2.0*(qy*qz + qw*qx),     1.0 - 2.0*(qx**2 + qy**2)]
    ], dtype=float)


def euler_to_quat(roll, pitch, yaw):
    """Converts Z-Y-X Euler angles (radians) to Hamiltonian unit quaternion [qw, qx, qy, qz]."""
    cy = math.cos(yaw * 0.5)
    sy = math.sin(yaw * 0.5)
    cp = math.cos(pitch * 0.5)
    sp = math.sin(pitch * 0.5)
    cr = math.cos(roll * 0.5)
    sr = math.sin(roll * 0.5)

    qw = cr * cp * cy + sr * sp * sy
    qx = sr * cp * cy - cr * sp * sy
    qy = cr * sp * cy + sr * cp * sy
    qz = cr * cp * sy - sr * sp * cy
    return np.array([qw, qx, qy, qz], dtype=float)


def quat_to_euler(q):
    """Converts Hamiltonian unit quaternion [qw, qx, qy, qz] to Euler angles [roll, pitch, yaw] (rad)."""
    q = q / np.linalg.norm(q)
    qw, qx, qy, qz = q

    # Roll (x-axis rotation)
    sinr_cosp = 2.0 * (qw * qx + qy * qz)
    cosr_cosp = 1.0 - 2.0 * (qx**2 + qy**2)
    roll = math.atan2(sinr_cosp, cosr_cosp)

    # Pitch (y-axis rotation)
    sinp = 2.0 * (qw * qy - qz * qx)
    if abs(sinp) >= 1.0:
        pitch = math.copysign(math.pi / 2.0, sinp)
    else:
        pitch = math.asin(sinp)

    # Yaw (z-axis rotation)
    siny_cosp = 2.0 * (qw * qz + qx * qy)
    cosy_cosp = 1.0 - 2.0 * (qy**2 + qz**2)
    yaw = math.atan2(siny_cosp, cosy_cosp)

    return np.array([roll, pitch, yaw], dtype=float)


def quat_derivative_casadi(q, omega):
    r"""
    Computes \dot{q} = 0.5 * q \otimes [0, \omega]^T for CasADi.
    omega is angular velocity in body frame B: [p, q, r]^T.
    """
    qw, qx, qy, qz = q[0], q[1], q[2], q[3]
    p, q_rate, r = omega[0], omega[1], omega[2]

    q_dot = 0.5 * cs.vertcat(
        -qx * p - qy * q_rate - qz * r,
         qw * p + qy * r      - qz * q_rate,
         qw * q_rate - qx * r + qz * p,
         qw * r + qx * q_rate - qy * p
    )
    return q_dot


def quat_error_so3_casadi(q, q_ref):
    r"""
    Calculates the attitude tracking error vector on SO(3) Lie algebra so(3).
    Equivalent to the vector part of q_err = q_ref^{-1} \otimes q.
    """
    qw, qx, qy, qz = q[0], q[1], q[2], q[3]
    qw_r, qx_r, qy_r, qz_r = q_ref[0], q_ref[1], q_ref[2], q_ref[3]

    # q_err = q_ref_conjugate * q
    err_x =  qw_r * qx - qx_r * qw - qy_r * qz + qz_r * qy
    err_y =  qw_r * qy + qx_r * qz - qy_r * qw - qz_r * qx
    err_z =  qw_r * qz - qx_r * qy + qy_r * qx - qz_r * qw

    return cs.vertcat(err_x, err_y, err_z)


def pod_unit_thrust_casadi(alpha_i, beta_i):
    r"""
    Returns unit thrust vector \hat{t}_i in Body Frame B generated by i-th pod (NED convention).
    Outer pitch angle alpha_i, Inner roll angle beta_i.
    In upright nominal position (alpha=0, beta=0), thrust pushes UP: [0, 0, -1]^T.
    \hat{t}_i = [ -sin(alpha)*cos(beta), -sin(beta), -cos(alpha)*cos(beta) ]^T
    """
    tx = -cs.sin(alpha_i) * cs.cos(beta_i)
    ty = -cs.sin(beta_i)
    tz = -cs.cos(alpha_i) * cs.cos(beta_i)
    return cs.vertcat(tx, ty, tz)


def pod_unit_thrust_numpy(alpha_i, beta_i):
    """Returns unit thrust vector in Body Frame B (NED convention: Upward hover is -Z)."""
    return np.array([
        -math.sin(alpha_i) * math.cos(beta_i),
        -math.sin(beta_i),
        -math.cos(alpha_i) * math.cos(beta_i)
    ], dtype=float)


def analytical_tilt_inversion(t_target):
    """
    Closed-form inversion mapping a desired 3D pod thrust vector t = [tx, ty, tz]
    to physical servo gimbal angles (alpha, beta) in NED frame (tz < 0 for upward lift).
    """
    norm_t = np.linalg.norm(t_target)
    if norm_t < 1e-4:
        return 0.0, 0.0

    # beta = -arcsin(ty / ||t||)
    sin_beta = -t_target[1] / norm_t
    sin_beta = np.clip(sin_beta, -1.0, 1.0)
    beta = math.asin(sin_beta)

    # In NED, upward thrust has negative tz:
    # alpha = -arcsin(tx / (||t|| * cos(beta)))
    cos_beta = math.cos(beta)
    if abs(cos_beta) < 1e-3:
        alpha = 0.0
    else:
        sin_alpha = -t_target[0] / (norm_t * cos_beta)
        sin_alpha = np.clip(sin_alpha, -1.0, 1.0)
        alpha = math.asin(sin_alpha)

    return alpha, beta
